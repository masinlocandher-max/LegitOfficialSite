export const SECTION_TYPES = Object.freeze([
  "offerings",
  "about",
  "gallery",
  "faq",
  "contact",
]);
export function templateById(id) {
  return TEMPLATES.find((t) => t.id === id);
}
export function createDraft(id = "atelier") {
  const t = templateById(id);
  if (!t) throw new Error("Choose a supported template.");
  return {
    schemaVersion: SCHEMA_VERSION,
    templateId: t.id,
    palette: t.palette,
    font: t.font,
    brand: t.brand,
    headline: t.headline,
    intro: t.intro,
    actionLabel: t.action,
    actionTarget: ["forma", "table", "frame"].includes(t.id)
      ? "offerings"
      : "contact",
    heroImage: t.image,
    heroAlt:
      t.image === "space"
        ? "Sample sunlit interior with a lounge chair"
        : t.image === "food"
          ? "Sample meal with grilled chicken, salad, and a citrus drink"
          : t.image
            ? "Sample ceramic vessel with an olive branch"
            : "",
    logo: "",
    logoAlt: "",
    description: t.intro,
    toolUrl: "",
    accent: "",
    imageFocus: "center",
    offeringsHeading: t.offerings,
    offerings: t.items.map(([title, body], i) => ({
      id: `item-${i + 1}`,
      title,
      body,
      detail: "",
      image: ["forma", "frame", "address", "stay"].includes(t.id)
        ? t.image || "ceramic"
        : "",
      alt: ["forma", "frame", "address", "stay"].includes(t.id)
        ? "Sample photograph; replace with your own"
        : "",
    })),
    aboutHeading: t.about,
    about:
      "Tell your story in your own words. Share who you are, what matters to you, and how you help the people you work with.",
    galleryHeading: "A closer look",
    gallery: [
      {
        id: "photo-1",
        image: t.image || "space",
        alt: "Sample photograph; replace with your own",
        caption: "Add your own photographs and captions.",
      },
    ],
    faqHeading: "A few helpful details",
    faqs: [
      {
        id: "faq-1",
        question: "How can we get started?",
        answer: "Use the contact details below to start a conversation.",
      },
    ],
    contactHeading: "Let’s start a conversation.",
    contactText: "Tell people the best way to reach you.",
    email: "",
    phone: "",
    location: "",
    externalUrl: "",
    externalLabel: "Visit our other page",
    sections: ["offerings", "about", "gallery", "faq", "contact"].map(
      (type) => ({ type, visible: type !== "gallery" && type !== "faq" }),
    ),
  };
}
export function changeTemplate(draft, id) {
  const template = templateById(id);
  if (!template) throw new Error("Choose a supported template.");
  return {
    ...structuredClone(draft),
    templateId: id,
    palette: template.palette,
    font: template.font,
  };
}
